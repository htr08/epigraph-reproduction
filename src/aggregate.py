"""Aggregate the per-run metrics written by eval_ensemble.py into summary tables.

Expected layout (created by notebooks/02_multiseed_robustness_kaggle.ipynb):

    runs/pretrained/metrics.json              author checkpoints
    runs/init_s<N>/metrics.json (+ train.log) experiment A: only weight init differs, split seed 30
    runs/split_s<N>/metrics.json (+ train.log) experiment B: fold split and init both differ

    python src/aggregate.py --runs runs --out results
"""
import argparse
import glob
import json
import os
import re

import numpy as np
from scipy import stats

KEYS = ["auc_roc", "auc_pr", "f1", "bacc", "mcc"]
LABEL = {"auc_roc": "AUC-ROC", "auc_pr": "AUC-PR", "f1": "F1", "bacc": "BACC", "mcc": "MCC"}
# Paper (Choi & Kim, Sci Rep 2024, 14:27496), Table 1 / Table 3, epitope3D test set
PAPER = {"auc_roc": 0.73, "auc_pr": 0.23, "f1": 0.29, "bacc": 0.62, "mcc": 0.19}
PAPER_ROUND = 0.005  # paper values are rounded to 2 decimals


def load_runs(runs_dir):
    runs = {}
    for path in sorted(glob.glob(os.path.join(runs_dir, "*", "metrics.json"))):
        name = os.path.basename(os.path.dirname(path))
        with open(path) as f:
            runs[name] = json.load(f)
        log = os.path.join(os.path.dirname(path), "train.log")
        if os.path.exists(log):
            runs[name]["_train"] = parse_train_log(log)
    return runs


def parse_train_log(path):
    txt = open(path, errors="ignore").read()
    ep = [int(x) for x in re.findall(r"The best epoch: (\d+)", txt)]
    vl = [float(x) for x in re.findall(r"The best val loss: ([0-9.]+)", txt)]
    va = [float(x) for x in re.findall(r"The best auc-roc: ([0-9.]+)", txt)]
    return {"best_epoch": ep, "best_val_loss": vl, "best_val_auc": va}


def ci_t(values, level=0.95):
    v = np.asarray(values, float)
    n = len(v)
    if n < 2:
        return float("nan"), float("nan")
    h = stats.t.ppf(0.5 + level / 2, n - 1) * v.std(ddof=1) / np.sqrt(n)
    return v.mean() - h, v.mean() + h


def fmt(x, d=3):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{d}f}"


def group_table(runs, names, title):
    out = [f"### {title}", ""]
    if not names:
        return out + ["_no runs found_", ""]
    out += ["| Run | " + " | ".join(LABEL[k] for k in KEYS) + " |", "|---|" + "---|" * len(KEYS)]
    for n in names:
        out.append(f"| {n} | " + " | ".join(fmt(runs[n]["ensemble"][k]) for k in KEYS) + " |")
    vals = {k: [runs[n]["ensemble"][k] for n in names] for k in KEYS}
    out.append("| **mean ± std** | " + " | ".join(
        f"**{np.mean(vals[k]):.3f} ± {np.std(vals[k], ddof=1) if len(names) > 1 else 0:.3f}**" for k in KEYS) + " |")
    out.append("| min – max | " + " | ".join(f"{min(vals[k]):.3f} – {max(vals[k]):.3f}" for k in KEYS) + " |")
    cis = {k: ci_t(vals[k]) for k in KEYS}
    out.append(f"| 95% t-interval of the mean (n={len(names)}) | " + " | ".join(
        f"[{fmt(cis[k][0])}, {fmt(cis[k][1])}]" for k in KEYS) + " |")
    out.append("| Paper value | " + " | ".join(f"{PAPER[k]:.2f}" for k in KEYS) + " |")
    verdict = []
    for k in KEYS:
        lo, hi = cis[k]
        if np.isnan(lo):
            verdict.append("n/a")
        else:
            verdict.append("inside" if lo - PAPER_ROUND <= PAPER[k] <= hi + PAPER_ROUND else "OUTSIDE")
    out.append("| Paper value within interval (±0.005 rounding)? | " + " | ".join(verdict) + " |")
    out.append("")

    # single models pooled over the group
    out += ["Single (non-ensembled) models, pooled over all folds of the group:", "",
            "| Metric | mean ± std over models | ensemble mean | ensemble gain |", "|---|---|---|---|"]
    for k in KEYS:
        allv = np.concatenate([runs[n]["single_models"][k]["values"] for n in names])
        out.append(f"| {LABEL[k]} | {allv.mean():.3f} ± {allv.std(ddof=1):.3f} (n={len(allv)}) | "
                   f"{np.mean(vals[k]):.3f} | {np.mean(vals[k]) - allv.mean():+.3f} |")
    out.append("")

    tr = [runs[n]["_train"] for n in names if "_train" in runs[n]]
    if tr:
        auc = [np.mean(t["best_val_auc"]) for t in tr if t["best_val_auc"]]
        ep = np.concatenate([t["best_epoch"] for t in tr if t["best_epoch"]])
        out.append(f"Validation side: mean best val AUC per run = {np.mean(auc):.3f} ± "
                   f"{np.std(auc, ddof=1) if len(auc) > 1 else 0:.3f}; best epoch median {np.median(ep):.0f} "
                   f"(range {ep.min()}–{ep.max()}, n={len(ep)} folds).")
        out.append("")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="runs")
    ap.add_argument("--out", default="results")
    a = ap.parse_args()
    runs = load_runs(a.runs)
    os.makedirs(a.out, exist_ok=True)

    md = ["# Multi-seed robustness summary (auto-generated by src/aggregate.py)", ""]
    if "pretrained" in runs:
        r = runs["pretrained"]
        ci = r["ensemble_ci95_bootstrap_antigens"]
        md += [f"## Author checkpoints on the test set ({r['n_antigens']} antigens, "
               f"{r['n_surface_residues']} surface residues, {100 * r['positive_rate']:.1f}% epitope)", "",
               "| Metric | Paper | Ensemble (10 models) | 95% bootstrap CI over antigens | Single-model mean ± std |",
               "|---|---|---|---|---|"]
        for k in KEYS:
            s = r["single_models"][k]
            md.append(f"| {LABEL[k]} | {PAPER[k]:.2f} | {r['ensemble'][k]:.3f} | "
                      f"[{ci[k][0]:.3f}, {ci[k][1]:.3f}] | {s['mean']:.3f} ± {s['std']:.3f} |")
        pa = r["per_antigen_auc_roc"]
        md += ["", f"Per-antigen AUC-ROC (ensemble): mean {pa['mean']:.3f}, median {pa['median']:.3f} "
                   f"over {pa['n_antigens_with_both_classes']} antigens.", ""]

    A = [n for n in runs if n.startswith("init_s")]
    B = [n for n in runs if n.startswith("split_s")]
    md += ["## Retrained models", ""]
    md += group_table(runs, A, "Experiment A - weight-initialisation seeds only (fold split fixed, seed 30)")
    md += group_table(runs, B, "Experiment B - fold split and initialisation both re-randomised")
    if "pretrained" in runs and (A or B):
        md += ["## Retrained vs. author checkpoints (ensemble AUC-ROC)", ""]
        pre = runs["pretrained"]["ensemble"]["auc_roc"]
        for title, g in (("A", A), ("B", B)):
            if g:
                v = [runs[n]["ensemble"]["auc_roc"] for n in g]
                md.append(f"- Experiment {title}: mean {np.mean(v):.3f} vs. author checkpoints {pre:.3f} "
                          f"(difference {np.mean(v) - pre:+.3f}).")
        md.append("")

    text = "\n".join(md)
    with open(os.path.join(a.out, "summary.md"), "w", encoding="utf-8") as f:
        f.write(text)
    with open(os.path.join(a.out, "summary.json"), "w") as f:
        json.dump({n: {k: v for k, v in r.items() if k != "_train"} for n, r in runs.items()}, f, indent=2)
    print(text)


if __name__ == "__main__":
    main()
